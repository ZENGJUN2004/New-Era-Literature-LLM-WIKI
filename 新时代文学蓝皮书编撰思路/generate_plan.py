def add_para(text='', size=11, bold=False, font='宋体', color=None, align=None, space_after=6, indent=None):
    p = doc.add_paragraph()
    if align:
        p.alignment = align
    if indent:
        p.paragraph_format.left_indent = Cm(indent)
    p.paragraph_format.space_after = Pt(space_after)
    if text:
        run = p.add_run(text)
        set_cn_font(run, font, size, bold, color)
    return p

def add_bullet(label, text, label_bold=True, label_color=RGBColor(0x1f, 0x49, 0x7d)):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.space_after = Pt(4)
    if label:
        r1 = p.add_run(label)
        set_cn_font(r1, '黑体', 11, True, label_color)
    r2 = p.add_run(text)
    set_cn_font(r2, '宋体', 11)
    return p

